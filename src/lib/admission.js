/**
 * 把階段標成已結束／進行中／尚未開始。
 * 在建置期以建置日判斷，網站每月自動重建，所以狀態會跟著更新。
 */
export function stageStatus(stage, today) {
  if (today > stage.end) return 'past';
  if (today >= stage.start) return 'now';
  return 'upcoming';
}

/** 整個學年度的日期都過完了，代表這份資料該更新了 */
export const isStale = (schedule, today) =>
  schedule.stages.every((s) => today > s.end);

